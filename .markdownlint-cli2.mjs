//
// - `kb/themes` is a submodule (heroiclands-hugo-theme); it lints itself in its
//   own repository.
//
// The shared configuration already supplies the rule set, `**/*.md` as the
// glob, `gitignore: true` (which covers the generated `kb/content/`,
// `kb/public/` and `build/` trees), and `CHANGELOG.md` — regenerated by
// `changeset version` in every repository here, so linting it reports on the
// generator.
//
// Spread rather than mutated: the shared objects are frozen, so an edit in
// place would fail loudly rather than quietly change the rules for everything
// else in the process.
