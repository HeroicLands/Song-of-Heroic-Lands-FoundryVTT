import * as prettier from "prettier";
import { formatNoteFrontmatter } from "@heroiclands/package-build/engine/note-format";

/**
 * Format generated file content with the shared Markdown and note-frontmatter
 * rules, so a generator emits a file the repository formatter accepts.
 *
 * SoHL-owned documentation generators write through this helper. Prettier
 * formats the Markdown body and the shared note formatter canonicalizes YAML
 * frontmatter. Generator checks compare against this same result, so
 * regeneration and `npm run format` agree. The item-field reference page is
 * generated by package-build.
 *
 * @param {string} text - The generated file content.
 * @param {string} filepath - Absolute path the content will be written to. Used
 *   to resolve the right parser and any per-file overrides from the Prettier
 *   config (e.g. markdown's narrower `tabWidth`).
 * @returns {Promise<string>} The content in the repository's canonical format.
 */
export async function formatGenerated(text, filepath) {
    const config = await prettier.resolveConfig(filepath);
    return formatNoteFrontmatter(await prettier.format(text, { ...config, filepath }));
}
