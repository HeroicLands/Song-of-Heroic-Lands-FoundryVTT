import { formatGenerated as formatWithPrettier } from "@heroiclands/package-build/engine";
import { formatNoteFrontmatter } from "@heroiclands/package-build/engine/note-format";

/**
 * Format generated file content with the shared Markdown rules, then
 * canonicalize its note frontmatter, so a generator emits a file the
 * repository formatter accepts.
 *
 * SoHL-owned documentation generators write through this helper. The shared
 * `formatGenerated` runs Prettier against the destination's own
 * configuration; `formatNoteFrontmatter` then reorders and reflows a content
 * note's YAML the way `package-build format --write` does. Generator checks
 * compare against this same result, so regeneration and `npm run format`
 * agree. Every generator that writes through this helper targets a content
 * note (`shortcode` and `type` in its frontmatter), which is why the
 * frontmatter step runs unconditionally — `formatNoteFrontmatter` is a no-op
 * on text without both keys. The item-field reference page is generated by
 * package-build.
 *
 * @param {string} text - The generated file content.
 * @param {string} filepath - Absolute path the content will be written to. Used
 *   to resolve the right parser and any per-file overrides from the Prettier
 *   config (e.g. markdown's narrower `tabWidth`).
 * @returns {Promise<string>} The content in the repository's canonical format.
 */
export async function formatGenerated(text, filepath) {
    return formatNoteFrontmatter(await formatWithPrettier(text, filepath));
}
