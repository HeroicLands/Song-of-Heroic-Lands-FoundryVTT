/*
 * Builds the icon assets the knowledgebase needs to render SoHL glyphs.
 *
 * In Foundry the system stylesheet is already loaded, so a `<i class="ginf-…">`
 * in a journal just works. The knowledgebase is a separate Hugo site that loads
 * neither Font Awesome nor the game-icons webfont, so the same markup renders as
 * nothing there. This emits a drop-in pair for the shared Hugo theme:
 *
 *   build/kb-icons/game-icons-kb.woff2  — the webfont, SUBSET to the glyphs the
 *                                         published docs actually reference
 *   build/kb-icons/sohl-icons.css       — @font-face + box metrics + those rules
 *
 * Subsetting matters: the full font is ~970 KB for 4176 glyphs, while the docs
 * reference barely a dozen. The subset reuses the persisted codepoint map, so a
 * class means the same glyph on the KB as it does in Foundry.
 *
 * Font Awesome is NOT vendored here. Its free set is available from a public CDN
 * and the theme already loads webfonts that way; vendoring it would also mean
 * shipping a font whose Foundry-bundled copy is the Pro distribution.
 *
 * Run: npm run build:kb-icons
 */

import { Buffer } from "buffer";
import { readFileSync, writeFileSync, mkdirSync } from "fs";
import { basename } from "path";
import { globSync } from "glob";
import svg2ttf from "svg2ttf";
import ttf2woff2 from "ttf2woff2";
import { buildSvgFont } from "./build-icon-font.mjs";

const ICONS_DIR = "assets/icons/game-icons";
const CODEPOINTS_PATH = "assets/icons/game-icons-codepoints.json";
const OUT_DIR = "build/kb-icons";
const WOFF2_NAME = "game-icons-kb.woff2";
const FONT_NAME = "game-icons.net";
const CLASS_PREFIX = "ginf-";

/* Kept in step with utils/build-icon-font.mjs — see the rationale there. */
const GLYPH_BOX_WIDTH = "1.25em";
const GLYPH_SCALE = "1.4em";
const GLYPH_BASELINE_SHIFT = "-0.30em";

/** Every `ginf-<name>` class referenced by the published documentation. */
function usedIconNames() {
    const re = new RegExp(`\\b${CLASS_PREFIX}([a-z0-9-]+)`, "g");
    const names = new Set();
    for (const file of [
        ...globSync("assets/content/**/*.md"),
        ...globSync("kb/dev-docs/**/*.md"),
    ]) {
        const text = readFileSync(file, "utf8");
        for (const m of text.matchAll(re)) names.add(m[1]);
    }
    return [...names].sort();
}

/** Resolve icon names to `{ name, path }`, failing loudly on a missing glyph. */
function resolveIcons(names) {
    const byName = new Map();
    for (const p of globSync(`${ICONS_DIR}/**/*.svg`).sort()) {
        const n = basename(p, ".svg");
        if (!byName.has(n)) byName.set(n, { name: n, path: p });
    }
    const missing = names.filter((n) => !byName.has(n));
    if (missing.length)
        throw new Error(
            `build-kb-icon-assets: documentation references unknown icon(s): ${missing.join(", ")}`,
        );
    return names.map((n) => byName.get(n));
}

/** The stylesheet the theme links; mirrors the generated SCSS rules. */
function renderCss(icons, codepoints) {
    const rules = icons
        .map(
            (i) =>
                `.${CLASS_PREFIX}${i.name}::before { content: "\\${codepoints[i.name].toString(
                    16,
                )}"; }`,
        )
        .join("\n");
    return `/*
 * SoHL icon glyphs for the knowledgebase.
 * AUTO-GENERATED by the SoHL repo (utils/build-kb-icon-assets.mjs) — do not edit
 * by hand. Regenerate with \`npm run build:kb-icons\` and copy both files across.
 *
 * Contains only the ${icons.length} game-icons glyph(s) the published docs use.
 * Font Awesome is loaded separately (its free set, from a CDN).
 *
 * Game-Icons.net artwork is CC BY 3.0 (CC0 for Viscious Speed and Zeromancer);
 * per-author credit lives in the SoHL repo at
 * assets/icons/game-icons/ATTRIBUTION.md.
 */
@font-face {
    font-display: block;
    font-family: "${FONT_NAME}";
    font-style: normal;
    font-weight: 400;
    src: url("../fonts/${WOFF2_NAME}") format("woff2");
}

[class^="${CLASS_PREFIX}"],
[class*=" ${CLASS_PREFIX}"] {
    display: inline-flex;
    align-items: center;
    justify-content: center;
    width: ${GLYPH_BOX_WIDTH};
    height: 1em;
    line-height: 1;
    vertical-align: ${GLYPH_BASELINE_SHIFT};
}

[class^="${CLASS_PREFIX}"]::before,
[class*=" ${CLASS_PREFIX}"]::before {
    font-family: "${FONT_NAME}" !important;
    font-style: normal;
    font-weight: normal;
    font-variant: normal;
    text-transform: none;
    line-height: 1;
    font-size: ${GLYPH_SCALE};
    speak: never;
    -webkit-font-smoothing: antialiased;
    -moz-osx-font-smoothing: grayscale;
}

${rules}
`;
}

async function main() {
    const names = usedIconNames();
    if (!names.length)
        throw new Error(
            "build-kb-icon-assets: no ginf- classes found in the documentation — " +
                "nothing to subset (has the legend been generated?).",
        );
    const icons = resolveIcons(names);
    const codepoints = JSON.parse(readFileSync(CODEPOINTS_PATH, "utf8"));

    const svgFont = await buildSvgFont(icons, codepoints);
    const ttf = svg2ttf(svgFont, { description: FONT_NAME, ts: 0 });
    const woff2 = ttf2woff2(Buffer.from(ttf.buffer));

    mkdirSync(OUT_DIR, { recursive: true });
    writeFileSync(`${OUT_DIR}/${WOFF2_NAME}`, woff2);
    writeFileSync(`${OUT_DIR}/sohl-icons.css`, renderCss(icons, codepoints));

    console.log(
        `✅ KB icon assets: ${icons.length} glyph(s) → ${OUT_DIR}/${WOFF2_NAME} ` +
            `(${(woff2.length / 1024).toFixed(1)} KB) + sohl-icons.css`,
    );
    console.log(`   glyphs: ${names.join(", ")}`);
}

main().catch((err) => {
    console.error(err);
    process.exit(1);
});
